#!/usr/bin/env python
"""Generate the two self-conditioned-evaluation tables from docs/w60_selfcond.json.

Kept separate from gen_tables.py because the source is a different artifact
(the W60 runs) with its own readiness state: before those runs finish, this
script emits tables whose cells are visibly unfilled rather than plausible
numbers, so a half-finished experiment cannot leak into the paper as fact.

  python scripts/gen_w60_tables.py            # writes both table files
"""
import json
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(HERE)

SRC = "artifacts/metrics/w60_selfcond.json"
if not os.path.isfile(SRC):
    SRC = "docs/w60_selfcond.json"
T1 = "artifacts/tables/selfcond.tex"
T2 = "artifacts/tables/selfcond_recover.tex"

PENDING = "\\textcolor{red}{--}"

ROWS = [
    ("dense", "Dense (no pruning)"),
    ("trace_c50_h10", "\\method{} $(50\\%,10\\%)$"),
    ("trace_c25_h05", "\\method{} $(25\\%,5\\%)$"),
]


def load():
    if not os.path.exists(SRC):
        print(f"note: {SRC} absent -- emitting placeholder tables")
        return {}
    with open(SRC, encoding="utf-8") as fh:
        return json.load(fh)


def num(v, fmt="{:.2f}"):
    return PENDING if v is None else fmt.format(v)


def signed(v):
    return PENDING if v is None else f"{v:+.2f}"


def ci(d, key="ci95_pp"):
    if not d or key not in d:
        return PENDING
    lo, hi = d[key]
    return f"[{lo:+.2f}, {hi:+.2f}]"


def table1(rep):
    t1 = rep.get("tier_i") or {}
    t2 = rep.get("tier_ii") or {}
    arms = t2.get("arms") or {}
    div = t2.get("divergence") or {}
    lines = [
        "% AUTO-GENERATED by scripts/gen_w60_tables.py",
        "\\begin{table}[t]",
        "    \\centering",
        "    \\caption{\\textbf{Self-conditioned evaluation on OmniGUI.} The"
        " carrier's own parsed action replaces the ground truth in the history"
        " and in the committed dialogue cache; frames remain the ground-truth"
        " trajectory. $\\Delta$ columns are self-conditioned minus"
        " teacher-forced on the identical step set. Episode success and goal"
        " progress are near-invariant by construction, since they score only"
        " the all-correct prefix on which the two histories coincide, so"
        " Step~SR is the quantity that moves. \\emph{Never div.} is the"
        " fraction of episodes whose predicted action type never departs from"
        " the reference.}",
        "    \\label{tab:selfcond}",
        "    \\adjustbox{max width=\\textwidth,center}{%",
        "        \\footnotesize",
        "        \\setlength{\\tabcolsep}{6pt}",
        "        \\renewcommand{\\arraystretch}{0.98}",
        "        \\begin{tabular}{l cc c ccc c}",
        "            \\toprule",
        "            & \\multicolumn{2}{c}{\\textbf{Step~SR}} & &"
        " \\multicolumn{3}{c}{\\textbf{Self-cond.\\ minus teacher-forced}} & \\\\",
        "            \\cmidrule(lr){2-3} \\cmidrule(lr){5-7}",
        "            \\textbf{Arm} & TF & Self-cond. & &"
        " $\\Delta$Step~SR & $\\Delta$SR & $\\Delta$GP & \\textbf{Never div.} \\\\",
        "            \\midrule",
    ]
    for key, label in ROWS:
        ti = t1.get(key) or {}
        tf = (ti.get("teacher_forced") or {}).get("step_sr_pct")
        sc = (ti.get("self_cond") or {}).get("step_sr_pct")
        if sc is None:
            sc = (arms.get(key) or {}).get("step_sr_pct")
        nd = (div.get(key) or {}).get("never_diverges_pct")
        lines.append(
            f"            {label} & {num(tf)} & {num(sc)} & &"
            f" {signed(ti.get('d_step_sr_pp'))} & {signed(ti.get('d_sr_pp'))} &"
            f" {signed(ti.get('d_gp_pp'))} & {num(nd, '{:.1f}')} \\\\"
        )
    lines += [
        "            \\midrule",
        "            \\multicolumn{8}{l}{\\textit{Paired dense $-$ \\method{},"
        " episode-clustered bootstrap (pp, $95\\%$ CI)}} \\\\",
    ]
    for key, label in ROWS[1:]:
        d = (t2.get(f"dense_minus_{key}") or {})
        s, t = d.get("self_cond"), d.get("teacher_forced")
        lines.append(
            f"            \\quad vs {label} & \\multicolumn{{7}}{{l}}{{"
            f"self-cond.\\ {signed((s or {}).get('delta_pp'))} {ci(s)};\\ \\ "
            f"teacher-forced {signed((t or {}).get('delta_pp'))} {ci(t)}}} \\\\"
        )
    lines += [
        "            \\bottomrule",
        "        \\end{tabular}%",
        "    }",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def table2(rep):
    t3 = rep.get("tier_iii") or {}
    rec = t3.get("recovery") or {}
    base = t3.get("clean_baseline") or {}
    dR = t3.get("delta_R_dense_minus_trace_c50_h10") or {}
    lines = [
        "% AUTO-GENERATED by scripts/gen_w60_tables.py",
        "\\begin{table}[t]",
        "    \\centering",
        "    \\caption{\\textbf{Recovery from a contaminated history.} One"
        " plausible but wrong navigation action, identical across arms for the"
        " same episode and step, is forced into the history at the first step;"
        " $R$ is the probability that the next step is still correct."
        " \\emph{Clean} is the same step under an uncontaminated history, which"
        " separates a hard step from a damaged history. The reported quantity is"
        " $\\Delta R$, paired on the episode with an episode-clustered"
        " bootstrap: an interval containing zero means the identical"
        " intervention leaves recoverability indistinguishable between the dense"
        " and the pruned cache.}",
        "    \\label{tab:selfcond-recover}",
        "    \\adjustbox{max width=\\textwidth,center}{%",
        "        \\footnotesize",
        "        \\setlength{\\tabcolsep}{7pt}",
        "        \\renewcommand{\\arraystretch}{0.98}",
        "        \\begin{tabular}{l ccc}",
        "            \\toprule",
        "            \\textbf{Arm} & \\textbf{Clean} & \\textbf{Contaminated"
        " ($R$)} & \\textbf{$95\\%$ CI on $R$} \\\\",
        "            \\midrule",
    ]
    for key, label in [ROWS[0], ROWS[1]]:
        r, b = rec.get(key) or {}, base.get(key) or {}
        lines.append(
            f"            {label} & {num(b.get('rate_pct'))} &"
            f" {num(r.get('rate_pct'))} & {ci(r, 'ci95_pct')} \\\\"
        )
    eps = f", {dR['n_episodes']} episodes" if dR.get("n_episodes") else ""
    cell = f"{signed(dR.get('delta_pp'))} pp, $95\\%$ CI {ci(dR)}{eps}"
    lines += [
        "            \\midrule",
        "            $\\Delta R$ (dense $-$ \\method{}) &"
        " \\multicolumn{3}{l}{" + cell + "} \\\\",
        "            \\bottomrule",
        "        \\end{tabular}%",
        "    }",
        "\\end{table}",
        "",
    ]
    return "\n".join(lines)


def main():
    rep = load()
    for path, body in ((T1, table1(rep)), (T2, table2(rep))):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(body)
        print(f"wrote {path}")
    if not rep:
        print("\nplaceholder cells are red '--'; rerun after "
              "scripts/_w60_selfcond_metrics.py produces docs/w60_selfcond.json")


if __name__ == "__main__":
    main()
