def _uitars_cell(block, arm):
    """(avg, col1, col2) as display strings; TBD when the cell has not landed."""
    v = block.get(arm)
    if v is None:
        return (TBD, TBD, TBD)
    avg = v * 100.0 if abs(v) <= 1.0 else v
    subs = block.get(f"{arm}_subs") or [None, None]
    out = [f"{avg:.2f}"]
    for s in subs[:2]:
        out.append(f"{s:.2f}" if isinstance(s, (int, float)) else DASH)
    return tuple(out)


def _uitars_ub():
    """Upper-bound row (own dense) as nine display strings."""
    data = _uitars_data()
    cells = []
    for b in UITARS_BENCHES:
        avg, c1, c2 = _uitars_cell(data.get(b) or {}, "dense")
        cells += [c1, c2, avg]
    return cells


def _uitars_budget_rows(suffix):
    """Rows for one budget band; Avg.(%) is retention against own dense."""
    data = _uitars_data()
    ub = []
    for b in UITARS_BENCHES:
        v = (data.get(b) or {}).get("dense")
        ub.append(v * 100.0 if (v is not None and abs(v) <= 1.0) else v)
    rows = []
    for label, arm_stem, kind in UITARS_ROWS:
        vals, ratios = [], []
        for bi, b in enumerate(UITARS_BENCHES):
            block = data.get(b) or {}
            arm = f"{arm_stem}_{suffix}"
            avg, c1, c2 = _uitars_cell(block, arm)
            vals += [c1, c2, avg]
            if fnum(avg) and ub[bi]:
                ratios.append(float(avg) / float(ub[bi]))
        # Retention must average the SAME three suites for every row: a partial
        # mean would let a row with one landed suite outrank a complete row.
        ret = (f"{100.0 * sum(ratios) / len(ratios):.1f}"
               if len(ratios) == len(UITARS_BENCHES) else TBD)
        rows.append((label, kind, vals + [ret]))
    return rows


