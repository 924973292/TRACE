def _ret_avg(pairs):
    """pairs: (val, ub) scalars or (val_list, ub_list) -> one averaged vote.
    Returns None when any component cell has not landed (TBD/DASH)."""
    votes = []
    for v, ub in pairs:
        if isinstance(v, (list, tuple)):
            subs = []
            for x, u in zip(v, ub):
                if not fnum(x):
                    return None
                subs.append(float(x) / u)
            votes.append(sum(subs) / len(subs))
        else:
            if not fnum(v):
                return None
            votes.append(float(v) / ub)
    return 100.0 * sum(votes) / len(votes)


