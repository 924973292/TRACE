M2W_COUNTS = (2008.0, 5429.0, 1343.0)  # task / domain / website official steps


def _m2w_pooled(tier_key, name):
    """Micro-pool [Ele.Acc, Op.F1, Step SR] over Mind2Web's three official
    splits (weighted by step counts) -- the same micro convention as the
    single-step sub-columns, so the pooled cells recombine exactly from the
    per-split appendix table. Returns None if any split cell has not landed."""
    tot = sum(M2W_COUNTS)
    acc = [0.0, 0.0, 0.0]
    for sk, n_s in zip(("task", "domain", "website"), M2W_COUNTS):
        vals, _ = _m2w_lookup(sk, tier_key, name)
        if vals is None:
            return None
        for j, x in enumerate(vals):
            if not fnum(x):
                return None
            acc[j] += float(x) * n_s
    return [f"{a / tot:.2f}" for a in acc]


def _m2w_pooled_ub():
    tot = sum(M2W_COUNTS)
    return [f"{sum(float(M2W_UB[3 * i + j]) * M2W_COUNTS[i] for i in range(3)) / tot:.2f}"
            for j in range(3)]


