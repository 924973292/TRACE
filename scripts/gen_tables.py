ILLM: set = set()

# Caption discipline, following the exemplars: a caption names what the table
# shows and declares its reading keys, nothing else. It never cites another
# float, a section, or an appendix, never quotes a number, and never states a
# conclusion. Protocol lives in the experiment prose, caveats in table notes.
#
# Reading keys are declared ONCE, in the first comparison table, and inherited
# silently by every later table. LEGEND therefore belongs only to
# tab:main-single; the other tables carry a bare descriptive title.
LEGEND = (r" \textbf{Avg.\,(\%)} denotes retained performance relative to the"
          r" full-token upper bound. Best and second-best results are shown in"
          r" \textbf{bold} and \underline{underlined}, respectively.")
TBD_NOTE = r" \tbd{} marks runs still in flight."


def _note_lines(notes, width=r"\textwidth"):
    # Protocol caveats sit under the rule as a note, not inside the caption.
    if not notes:
        return []
    return [
        r"    \vspace{2pt}",
        r"    \begin{minipage}{" + (width or r"\textwidth") + r"}",
        r"        \scriptsize " + notes,
        r"    \end{minipage}",
    ]


def wrap_table(label, caption, body_lines, tall=False, tabcolsep="7pt",
               arraystretch="0.98", wrap_width=None, notes=None):
    # Drop the in-flight note automatically once every cell has landed.
    if TBD_NOTE in caption and not any(r"\tbd{}" in ln for ln in body_lines):
        caption = caption.replace(TBD_NOTE, "")
    # A wrap_width turns the table into a wrapfig `wraptable`, which the text
    # flows around. Used for the compact cross-backbone table so it costs a
    # column rather than a float of its own.
    if wrap_width:
        L = [
            "% AUTO-GENERATED by scripts/gen_tables.py",
            r"\begin{wraptable}{r}{" + wrap_width + r"}",
            r"    \centering",
            r"    \vspace{-\intextsep}",
            r"    \caption{" + caption + r"}",
            r"    \label{" + label + r"}",
            r"    \adjustbox{max width=" + wrap_width + r",center}{%",
            r"        \scriptsize",
            r"        \setlength{\tabcolsep}{" + tabcolsep + r"}",
            r"        \renewcommand{\arraystretch}{" + arraystretch + r"}",
        ]
        L.extend(body_lines)
        L.append(r"    }")
        L.extend(_note_lines(notes, wrap_width))
        L.append(r"\end{wraptable}")
        return "\n".join(L) + "\n"
    L = [
        "% AUTO-GENERATED by scripts/gen_tables.py",
        r"\begin{table}[t]",
        r"    \centering",
        r"    \caption{" + caption + r"}",
        r"    \label{" + label + r"}",
    ]
    if tall:
        L.append(r"    \adjustbox{max width=\textwidth,max totalheight=0.70\textheight,center}{%")
        L.append(r"        \scriptsize")
    else:
        L.append(r"    \adjustbox{max width=\textwidth,center}{%")
        L.append(r"        \footnotesize")
    L.append(r"        \setlength{\tabcolsep}{" + tabcolsep + r"}")
    L.append(r"        \renewcommand{\arraystretch}{" + arraystretch + r"}")
    L.extend(body_lines)
    L.append(r"    }")
    L.extend(_note_lines(notes))
    L.append(r"\end{table}")
    return "\n".join(L) + "\n"


def fnum(v):
    try:
        float(v)
        return True
    except (TypeError, ValueError):
        return False


def is_skip(name):
    return name in SKIP


def filter_rows(rows):
    return [r for r in rows if not is_skip(r[0])]


def rank_marks(rows, n_cols, higher, skip_cols=None):
    marks = [["" for _ in range(n_cols)] for _ in rows]
    for c in range(n_cols):
        if skip_cols and c in skip_cols:
            continue
        vals = []
        for ri, (name, kind, v) in enumerate(rows):
            if kind == "gray" or (isinstance(name, str) and name in ILLM):
                continue
            if c < len(v) and fnum(v[c]):
                vals.append((float(v[c]), ri))
        if not vals:
            continue
        hb = higher[c] if isinstance(higher, (list, tuple)) else higher
        uniq = sorted({x for x, _ in vals}, reverse=hb)
        best, second = uniq[0], uniq[1] if len(uniq) > 1 else None
        for x, ri in vals:
            if x == best:
                marks[ri][c] = "b"
            elif second is not None and x == second:
                marks[ri][c] = "u"
    return marks


def render_cell(raw, mark):
    s = str(raw)
    if mark == "b":
        return r"\textbf{" + s + "}"
    if mark == "u":
        return r"\underline{" + s + "}"
    return s


def group_order(rows):
    """Stable partition: gray anchors, input-level, in-LLM subgroup, ours."""
    def key(row):
        name, kind, _ = row
        if kind == "gray":
            return 0
        if kind == "ours":
            return 3
        if isinstance(name, str) and name in ILLM:
            return 2
        return 1
    return sorted(rows, key=key)


def render_rows(rows, n_cols, higher, gap_after=None, skip_cols=None):
    rows = group_order(rows)
    marks = rank_marks(rows, n_cols, higher, skip_cols=skip_cols)
    out = []
    for ri, (name, kind, vals) in enumerate(rows):
        illm = isinstance(name, str) and name in ILLM
        cells = []
        for c in range(n_cols):
            raw = vals[c] if c < len(vals) else DASH
            if kind == "gray":
                cells.append(r"\textcolor{gray}{" + str(raw) + "}")
            elif illm:
                cells.append(r"\inllm{" + str(raw) + "}")
            else:
                cells.append(render_cell(raw, marks[ri][c]))
            if gap_after and c in gap_after:
                cells.append("")
        if isinstance(name, tuple):
            nm = " & ".join(str(x) for x in name)
        elif kind == "ours":
            nm = r"\textbf{" + name + "}"
        elif kind == "gray":
            nm = r"\textcolor{gray}{" + name + "}"
        elif illm:
            nm = r"\inllm{" + name + "}"
        else:
            nm = name
        prefix = r"\rowcolor{rowblue}" if kind == "ours" else ""
        out.append("            " + prefix + nm + " & " + " & ".join(cells) + r" \\")
    return out


def band(text, total_cols):
    return (r"            \rowcolor{headergray}\multicolumn{" + str(total_cols)
            + r"}{c}{\textsc{" + text + r"}} \\")


