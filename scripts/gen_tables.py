def gen_main_efficiency():
    """ERA-style efficiency anatomy on OmniGUI Tier I (c50/h10).

    Latency/memory columns come from the co-located lat2 probe (200
    episodes, one GPU, CUDA-synchronized; scripts/_lat2_aggregate.py);
    PruneSID from its full-run native probe. Step SR is the
    full 708-episode headline number from the main table; Ret.(%) is
    Step SR / dense upper bound (52.45).
    """
    ub_sr = EFF_UB_SR
    rows_raw = EFF_ROWS
    rows = []
    for name, kind, tok, gf, sel, ttft, e2e, kv, sr in rows_raw:
        ret = "100.0" if kind == "gray" else f"{float(sr) / ub_sr * 100:.1f}"
        rows.append((name, kind, [tok, gf, sel, ttft, e2e, kv, sr, ret]))
    # lower-is-better for cost columns, higher for SR/Ret.
    higher = [False, False, False, False, False, False, True, True]
    n, tot = 8, 9
    body = [
        r"        \begin{tabular}{l cc c cc c cc}",
        r"            \toprule",
        r"            \textbf{Method} & \textbf{In.Tok} & \textbf{GFLOPs} & \textbf{Sel.\,(ms)} & \textbf{TTFT\,(ms)} & \textbf{E2E\,(ms)} & \textbf{KV\,(MB)} & \textbf{Step~SR} & \textbf{Ret.\,(\%)} \\",
        r"            \midrule",
    ]
    body.extend(render_rows(rows, n, higher))
    body += [r"            \bottomrule", r"        \end{tabular}"]
    return wrap_table(
        "tab:main-efficiency",
        r"\textbf{Per-step compute, latency, and cache size on OmniGUI} at the mild budget"
        r" ($\keepc{=}50\%$, $\keeph{=}10\%$). \textbf{Ret.\,(\%)} is OmniGUI"
        r" Step~SR against the dense OmniGUI upper bound. Costs are measured"
        r" on one CUDA-synchronized GPU. \method{}'s pixel-input detector runs"
        r" concurrently with the vision encode on the same GPU, so"
        r" \textbf{Sel.\,(ms)} reports the measured critical-path"
        r" selection-plus-detection residual (join $\leq$3\,ms); the detector's"
        r" full $\approx$112\,ms wall clock is dissected in"
        r" Appendix~\ref{app:efficiency}.",
        body,
        tabcolsep="5pt",
        arraystretch="0.96",
    )


def _print_harvest_status():
    """GUI-Owl table bodies are frozen literals. A harvest JSON is evidence
    that a rerun finished; it does not silently rewrite this generator."""
    import json
    path = os.path.join(_METRICS, "harvested_main.json")
    print("NOTE: GUI-Owl tables in this file are published snapshots.")
    print("      Re-running eval does not update them. After a GPU rerun,")
    print("      python scripts/harvest_paper_metrics.py and compare.")
    if not os.path.isfile(path):
        print("      no artifacts/metrics/harvested_main.json (GPU harvest not present)")
        return
    try:
        blob = json.loads(open(path, encoding="utf-8").read())
    except (OSError, ValueError):
        print("      harvested_main.json unreadable")
        return
    cells = blob.get("cells") or []
    if not cells:
        print("      harvested_main.json has no cells")
        return
    print("      harvested vs published (adopted TRACE cells):")
    for cell in cells:
        hid = cell.get("id", "?")
        pub = cell.get("published")
        got = cell.get("harvested")
        status = cell.get("status", "?")
        print(f"        {hid:24s} harvested={got} published={pub} [{status}]")


